import logging

from django.core.exceptions import ObjectDoesNotExist
from django.core.exceptions import ValidationError as DjangoValidationError
from django.db import IntegrityError
from django.http import Http404
from rest_framework import exceptions, status
from rest_framework.response import Response
from rest_framework.views import exception_handler

logger = logging.getLogger(__name__)


class PrivilegeEscalationError(exceptions.APIException):
    """
    Raised when a client attempts to escalate privileges via an unauthorized endpoint.

    Returns HTTP 403 Forbidden with a distinguishing error_code in the response body.
    Used by hardened serializers to block and audit privilege injection attempts
    (e.g., submitting role=admin to the public registration endpoint).
    """

    status_code = status.HTTP_403_FORBIDDEN
    default_detail = "Privilege escalation attempt detected and blocked."
    default_code = "privilege_escalation_attempt"


def custom_exception_handler(exc, context):
    # Map Django core exceptions to REST framework exceptions before default handler
    if isinstance(exc, DjangoValidationError):
        if hasattr(exc, "message_dict"):
            exc = exceptions.ValidationError(detail=exc.message_dict)
        elif hasattr(exc, "messages"):
            exc = exceptions.ValidationError(detail=exc.messages)
        else:
            exc = exceptions.ValidationError(detail=str(exc))
    elif isinstance(exc, ObjectDoesNotExist) or isinstance(exc, Http404):
        exc = exceptions.NotFound(detail=str(exc) if str(exc) else "Requested object not found.")
    elif isinstance(exc, IntegrityError):
        exc = exceptions.ValidationError(
            detail={
                "non_field_errors": ["A database constraint failure occurred (duplicate key or integrity violation)."]
            }
        )

    response = exception_handler(exc, context)

    import uuid

    correlation_id = str(uuid.uuid4())

    # 1. Unhandled server exceptions (500 Error)
    if response is None:
        view = context.get("view")
        view_name = view.__class__.__name__ if view else "UnknownView"
        logger.exception("Unhandled Server Exception [%s] in %s: %s", correlation_id, view_name, exc)

        return Response(
            {
                "error": {
                    "status": status.HTTP_500_INTERNAL_SERVER_ERROR,
                    "detail": "حدث خطأ غير متوقع في الخادم، يرجى المحاولة لاحقاً.",
                    "code": "SERVER_ERROR",
                    "correlation_id": correlation_id,
                    "errors": None,
                }
            },
            status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        )

    # 2. Server Errors (>= 500) generated by APIException
    if response.status_code >= 500:
        logger.error("Server Error [%s] (%s): %s", correlation_id, response.status_code, response.data)
        response.data = {
            "error": {
                "status": response.status_code,
                "detail": "حدث خطأ غير متوقع في الخادم، يرجى المحاولة لاحقاً.",
                "code": "SERVER_ERROR",
                "correlation_id": correlation_id,
                "errors": None,
            }
        }
        return response

    # 3. Client Errors (4xx) - Format consistently
    data = response.data
    detail = None
    errors = None

    if isinstance(data, dict):
        detail = data.get("detail")
        field_errors = {k: v for k, v in data.items() if k != "detail"}
        if field_errors:
            errors = field_errors
        if detail is not None:
            detail = str(detail)
    elif isinstance(data, list):
        detail = "; ".join(str(item) for item in data)
    else:
        detail = str(data)

    default_detail = "يرجى مراجعة البيانات المدخلة وتصحيح الأخطاء الموضحة." if errors else "Request failed"
    response.data = {
        "error": {
            "status": response.status_code,
            "detail": detail or default_detail,
            "errors": errors,
        }
    }

    if isinstance(data, dict):
        for extra_key in ("code", "course_id", "expired_at", "can_renew"):
            if extra_key in data:
                response.data[extra_key] = data[extra_key]
                response.data["error"][extra_key] = data[extra_key]

    # Inject distinguishable error_code for security-related exceptions
    if isinstance(exc, PrivilegeEscalationError):
        response.data["error"]["error_code"] = "PRIVILEGE_ESCALATION_ATTEMPT"

    return response
