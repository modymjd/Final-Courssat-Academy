#!/usr/bin/env python3
"""
EduSmart Platform - Schemathesis API Fuzzing Runner
Runs property-based API testing against the OpenAPI schema generated by DRF Spectacular.
"""

import json
import os
import shutil
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request

ALLOWED_DEV_HOSTS = {"localhost", "127.0.0.1", "::1", "0.0.0.0", "testserver"}


def is_local_dev_target(url: str) -> bool:
    parsed = urllib.parse.urlparse(url)
    hostname = (parsed.hostname or "").lower()
    return hostname in ALLOWED_DEV_HOSTS


def resolve_schemathesis_executable():
    venv_dir = os.path.dirname(sys.executable)
    exe_candidate = os.path.join(venv_dir, "schemathesis.exe")
    if os.path.isfile(exe_candidate):
        return exe_candidate

    path_exe = shutil.which("schemathesis")
    if path_exe:
        return path_exe

    return None


def obtain_jwt_token(base_url: str) -> str | None:
    token = os.environ.get("FUZZ_JWT_TOKEN")
    if token:
        print("[+] Using JWT authentication token from environment variable FUZZ_JWT_TOKEN.")
        return token

    # Auto-login is strictly restricted to local development environments
    if not is_local_dev_target(base_url):
        print("[!] SECURITY GUARD: Auto-login disabled for non-local targets.")
        return None

    login_url = f"{base_url.rstrip('/')}/api/v1/auth/login/"
    register_url = f"{base_url.rstrip('/')}/api/v1/auth/register/"
    credentials = {
        "email": "fuzz_user@example.com",
        "password": "FuzzUserPass123!",
    }

    print("[*] Attempting auto-login for local fuzz test user (fuzz_user@example.com)...")
    try:
        req = urllib.request.Request(
            login_url,
            data=json.dumps(credentials).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=5) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            access_token = data.get("access")
            if access_token:
                print("[+] Auto-login successful for local fuzz test user.")
                return str(access_token)
    except urllib.error.HTTPError as e:
        if e.code in (400, 401):
            print("[*] Test user not found. Attempting local registration...")
            reg_payload = {
                **credentials,
                "first_name": "Fuzz",
                "last_name": "User",
            }
            try:
                reg_req = urllib.request.Request(
                    register_url,
                    data=json.dumps(reg_payload).encode("utf-8"),
                    headers={"Content-Type": "application/json"},
                    method="POST",
                )
                with urllib.request.urlopen(reg_req, timeout=5) as reg_resp:
                    reg_data = json.loads(reg_resp.read().decode("utf-8"))
                    access_token = reg_data.get("access")
                    if access_token:
                        print("[+] Fuzz test user registered and authenticated successfully.")
                        return str(access_token)
            except Exception as reg_err:
                print(f"[!] Registration attempt skipped/failed: {reg_err}")
    except Exception as err:
        print(f"[!] Auto-login connection skipped: {err}")

    print("[!] Proceeding without authentication token.")
    return None


def run_fuzzing(schema_url="http://localhost:8000/api/schema/"):
    parsed = urllib.parse.urlparse(schema_url)
    if not is_local_dev_target(schema_url):
        print(
            f"[!] SECURITY ERROR: Fuzzing target host '{parsed.hostname}' is not in allowed local dev hosts ({ALLOWED_DEV_HOSTS}). Execution aborted."
        )
        sys.exit(1)

    exe = resolve_schemathesis_executable()
    if not exe:
        print("[!] Schemathesis CLI not found. Install via: pip install schemathesis")
        sys.exit(1)

    base_api_url = f"{parsed.scheme}://{parsed.netloc}"
    token = obtain_jwt_token(base_api_url)

    print(f"[*] Launching Schemathesis API Fuzzing against: {schema_url}")
    cmd = [
        exe,
        "run",
        schema_url,
        "-c",
        "not_a_server_error",
        "-c",
        "status_code_conformance",
        "-c",
        "response_schema_conformance",
        "-w",
        "2",
        "--wait-for-schema=15",
        "--no-color",
    ]

    if token:
        print("[+] Authorization Header configured: Bearer [REDACTED_JWT_TOKEN]")
        cmd.extend(["-H", f"Authorization: Bearer {token}"])

    env = os.environ.copy()
    env["PYTHONIOENCODING"] = "utf-8"

    res = subprocess.run(cmd, env=env)
    sys.exit(res.returncode)


if __name__ == "__main__":
    url = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8000/api/schema/"
    run_fuzzing(url)
